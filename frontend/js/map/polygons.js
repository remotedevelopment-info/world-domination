/**
 * Returns non-overlapping [x, y] normalized label coordinates for a kingdom
 * at the given simulation year so parent empires never collide with successor states.
 */
export function getKingdomLabelPosition(code, poly, currentYear = 1500) {
  if (code === "KAL") {
    if (currentYear >= 1860) return [0.46, 0.312]; // Denmark / Jutland seat
    if (currentYear >= 1750) return [0.435, 0.215]; // Western Norway-Denmark
    return [0.485, 0.195]; // Full Kalmar Union center
  }
  if (code === "OTT") return [0.765, 0.642]; // Anatolian heartland
  if (code === "HRE") return [0.445, 0.448]; // German heartland
  if (code === "RUS") return [0.805, 0.265]; // Muscovy heartland
  if (code === "POL") return [0.625, 0.415]; // Vistula heartland
  if (code === "FRA") return [0.335, 0.525]; // French heartland
  if (code === "ESP") return [0.242, 0.705]; // Castilian-Aragonese heartland
  if (code === "VEN") return [0.522, 0.548]; // Venice lagoon

  if (!poly || !poly.length) return [0.5, 0.5];
  let x = 0;
  let y = 0;
  poly.forEach(([px, py]) => {
    x += px;
    y += py;
  });
  return [x / poly.length, y / poly.length];
}


