/**
 * Returns non-overlapping [x, y] normalized label coordinates for a kingdom
 * at the given simulation year so parent empires never collide with successor states.
 */
export function getKingdomLabelPosition(code, poly, currentYear = 1500) {
  if (code === "KAL") {
    if (currentYear >= 1750) return [0.5222, 0.1862]; // Norway / Skagerrak seat of Kalmar
  }
  if (code === "GEN") {
    if (currentYear >= 1860) return [0.5244, 0.2841]; // Ligurian coast
  }
  if (code === "OTT") {
    if (currentYear >= 1920) return [0.5750, 0.3034]; // Thrace / Edirne
  }
  if (code === "POL") {
    if (currentYear >= 1920) return [0.5694, 0.2103]; // Lithuania / Vilnius
  }
  if (code === "PRU") {
    if (currentYear >= 1920) return [0.5569, 0.2103]; // East Prussia / Königsberg
  }
  if (code === "MOR") {
    if (currentYear >= 1920) return [0.4806, 0.3724]; // South Morocco
  }
  if (code === "MUG") {
    if (currentYear >= 1920) return [0.7139, 0.3862]; // Upper Doab
  }
  if (code === "SRB") {
    if (currentYear >= 1920) return [0.5589, 0.2841]; // Morava
  }
  if (code === "CZE_SLO") {
    if (currentYear >= 1989) return [0.5500, 0.2510]; // Slovakia
  }
  if (code === "YUG") {
    if (currentYear >= 1989) return [0.5569, 0.2793]; // Belgrade
  }
  if (code === "KOR") {
    if (currentYear >= 1989) return [0.8533, 0.3345]; // Seoul
  }
  if (code === "CRO") {
    return [0.5444, 0.2724]; // Zagreb
  }
  if (code === "VNM") {
    return [0.7944, 0.4759]; // Central Vietnam
  }
  if (kingdomLabelPositions[code]) {
    return kingdomLabelPositions[code];
  }
  if (!poly || !poly.length) return [0.5, 0.5];
  let x = 0;
  let y = 0;
  poly.forEach(([px, py]) => {
    x += px;
    y += py;
  });
  return [x / poly.length, y / poly.length];
}
